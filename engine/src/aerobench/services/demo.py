"""Ready-made demo project: the Ahmed body, set up so every workflow step can be tried at once.

The Ahmed body (Ahmed, Ramm & Faltin, SAE 840300) is generated by the application itself,
so the demo needs no files. The project comes with

* a coarse mesh (about 0.25 M cells) and named refinement regions over the rear slant and
  the near wake, so the Mesh page shows how regions work;
* shape zones over the rear slant, the rear taper and the underbody exit, so the Optimise
  page can explore shape changes straight away;
* a run length that keeps a first run to a few minutes on a laptop (it stops early once
  converged).

Its notes and the ``demo`` tag make the app show a short guide on each page.
"""

from __future__ import annotations

import re
import tempfile
from pathlib import Path
from typing import Optional

from ..domain.mesh import BoxShape, RefinementRegion, RegionKind
from ..domain.project import ProjectConfig
from ..project.store import Project

DEMO_NAME = "Ahmed body demo"
DEMO_TAGS = ["demo", "ahmed"]


def _unique_dir(parent: Path, name: str) -> Path:
    base = re.sub(r"[^A-Za-z0-9_-]+", "_", name).strip("_") or "demo"
    p = parent / base
    k = 2
    while p.exists():
        p = parent / f"{base}_{k}"
        k += 1
    return p


def demo_regions() -> list[RefinementRegion]:
    """Refinement regions placed on the Ahmed body (CFD frame: nose at x = 0, ground z = 0)."""
    return [
        RefinementRegion(id="demo_slant", name="Rear slant and base", kind=RegionKind.USER, auto=False, level=4,
                         shape=BoxShape(min=(0.78, -0.25, 0.03), max=(1.10, 0.25, 0.40))),
        RefinementRegion(id="demo_wake", name="Wake behind the slant", kind=RegionKind.USER, auto=False, level=3,
                         shape=BoxShape(min=(1.04, -0.28, 0.0), max=(1.60, 0.28, 0.40))),
    ]


def demo_zones() -> list[dict]:
    """Shape zones: slant angle, rear taper (boat-tailing) and underbody exit (diffuser)."""
    return [
        {"id": "slant", "name": "Rear slant", "preset": "demo", "box_min": [0.74, -0.25, 0.20], "box_max": [1.10, 0.25, 0.40],
         "blend": 0.05, "moves": [{"direction": "z", "max_mm": 25, "segments": 2}], "symmetric": True, "enabled": True},
        {"id": "taper", "name": "Rear taper", "preset": "demo", "box_min": [0.74, -0.25, 0.02], "box_max": [1.10, 0.25, 0.40],
         "blend": 0.06, "moves": [{"direction": "width", "max_mm": 20, "segments": 2}], "symmetric": True, "enabled": True},
        {"id": "underbody", "name": "Underbody exit", "preset": "demo", "box_min": [0.75, -0.25, 0.0], "box_max": [1.10, 0.25, 0.12],
         "blend": 0.05, "moves": [{"direction": "z", "max_mm": 15, "segments": 2}], "symmetric": True, "enabled": False},
    ]


def create_ahmed_demo(parent: Path, cores: Optional[int] = None) -> Project:
    from ..geometry.fixtures import ahmed_body
    from ..geometry.io import write_stl
    from ..validation.benchmarks import _ahmed_configure
    from .geometry import import_geometry, refresh_derived
    from .zones import set_zones

    parent = Path(parent)
    parent.mkdir(parents=True, exist_ok=True)
    root = _unique_dir(parent, DEMO_NAME)
    p = Project.create(root, DEMO_NAME)
    with tempfile.TemporaryDirectory() as td:
        stl = Path(td) / "ahmed25.stl"
        write_stl(stl, ahmed_body(slant_deg=25.0, stilts=True))
        import_geometry(p, stl, units="m", label="Ahmed body, 25° slant (generated)")

    def configure(c: ProjectConfig) -> None:
        _ahmed_configure(c, "coarse")
        c.mesh.regions = demo_regions()
        c.numerics.iterations = 800
        c.numerics.stop_when_converged = True
        if cores:
            c.execution.n_procs = max(1, int(cores))
        c.tags = list(DEMO_TAGS)
        c.notes = ("Demo project: the Ahmed body (Ahmed, Ramm & Faltin, SAE 840300, 1984) at 40 m/s over a stationary ground. "
                   "Measured drag coefficient about 0.29-0.30 for the 25° slant; steady RANS on this coarse mesh typically gives "
                   "0.33-0.37. The mesh, refinement regions and shape zones are set up; run it, look at the results, then try "
                   "an optimisation of the rear slant on the Optimise page.")

    p.update(configure)
    refresh_derived(p)
    p.update(lambda c: _ahmed_configure_reference(c))
    set_zones(p, demo_zones())  # the stilts are never reshaped: zones leave stilts and wheels out
    return p


def _ahmed_configure_reference(c: ProjectConfig) -> None:
    """Reference area and length of the experiments (re-applied after derivation)."""
    from ..domain.setup import AreaSource

    c.reference.area = 0.389 * 0.288
    c.reference.area_source = AreaSource.MANUAL
    c.reference.length = 1.044
    c.reference.length_source = "manual"
