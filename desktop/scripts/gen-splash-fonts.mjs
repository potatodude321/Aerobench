// Embeds the two faces the launch window uses (it must render before anything is loaded
// from disk). Run after changing fonts: node scripts/gen-splash-fonts.mjs
import fs from "node:fs";
const f = (p) => fs.readFileSync(new URL(`../node_modules/@fontsource/${p}`, import.meta.url)).toString("base64");
const out = `// Generated by scripts/gen-splash-fonts.mjs (Barlow, SIL Open Font License 1.1). Do not edit.
export const SPLASH_FONT_TITLE = "${f("barlow-semi-condensed/files/barlow-semi-condensed-latin-600-normal.woff2")}";
export const SPLASH_FONT_TEXT = "${f("barlow/files/barlow-latin-400-normal.woff2")}";
`;
fs.writeFileSync(new URL("../electron/splashFonts.ts", import.meta.url), out);
console.log("electron/splashFonts.ts", out.length, "bytes");
