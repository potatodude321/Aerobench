"""Pack the large, rarely changing parts of the installation into separate archives so the
setup can update an existing installation in place (see components.py).

    python packaging/make_components.py [--build packaging/build] [--sevenzip PATH]

Run after prepare_thirdparty.py and prepare_python.py, before electron-builder. Writes

    packaging/build/components/archives/<name>-<id>.7z      embedded by the setup
    packaging/build/components/tools/components.py         installed as resources/tools/
    packaging/build/components/tools/components/<name>.json   file manifests
    desktop/build-resources/components.nsh                 NSIS defines (generated)

An archive is reused while its content (the id) is unchanged, so only changed components are
compressed again.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from components import FORMAT, MARKER, component_id, iter_files, sha256_file

ROOT = Path(__file__).resolve().parents[1]


def find_7z(explicit: str | None) -> str:
    cands = [explicit, os.environ.get("SEVENZIP"), shutil.which("7za"), shutil.which("7z"), shutil.which("7z.exe"),
             r"C:\Program Files\7-Zip\7z.exe"]
    cache = Path.home() / ".cache" / "electron-builder"
    cands += [str(p) for p in sorted(cache.glob("7zip*/*/bin/7za"))]
    for c in cands:
        if c and Path(c).is_file():
            return c
    sys.exit("7-Zip not found: install it or pass --sevenzip")


def nsis_str(s: str) -> str:
    return s.replace("$", "$$").replace('"', '$\\"')


def build(args: argparse.Namespace) -> int:
    b = Path(args.build).resolve()
    bundle_info = json.loads((b / "bundle" / "bundle.json").read_text(encoding="utf-8"))
    comps = bundle_info["components"]
    links = json.loads((b / "bundle" / "tools" / "paraview-links.json").read_text(encoding="utf-8"))
    pv_dir = Path(comps["paraview"]["path"]).name
    dll = next((p.stem for p in (b / "python").glob("python3?*.dll")), "python3")  # python312 -> 3.12
    of_root = comps["openfoam"]["path"].split("/", 1)[1]  # OpenFOAM-v2606
    of_key = next((b / "bundle" / "openfoam" / of_root / "platforms").glob("*/bin/simpleFoam.exe"), None)
    if of_key is None:
        sys.exit("simpleFoam.exe not found in the OpenFOAM bundle")
    # (name, source folder, folder under resources, label shown by the setup, key file)
    specs = [
        ("python", b / "python", "python", f"Python {dll[6]}.{dll[7:]}", "python.exe"),
        ("openfoam", b / "bundle" / "openfoam", "openfoam", f"OpenFOAM {comps['openfoam']['version']}",
         of_key.relative_to(b / "bundle" / "openfoam").as_posix()),
        ("paraview", b / "bundle" / pv_dir, pv_dir, f"ParaView {comps['paraview']['version']}", "bin/pvpython.exe"),
    ]
    out = b / "components"
    arch_dir, tools_dir = out / "archives", out / "tools"
    man_dir = tools_dir / "components"
    for d in (arch_dir, man_dir):
        d.mkdir(parents=True, exist_ok=True)
    shutil.copy2(Path(__file__).with_name("components.py"), tools_dir / "components.py")
    seven = find_7z(args.sevenzip)
    # file hashes are reused while size and modification time are unchanged (faster rebuilds)
    cache_file = out / "hash-cache.json"
    try:
        cache = json.loads(cache_file.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        cache = {}
    nsh = ["; generated by packaging/make_components.py - do not edit", f"!define AB_COMPONENTS_FORMAT {FORMAT}"]
    total_kb = 0
    for name, src, dirname, label, key in specs:
        if not src.is_dir():
            sys.exit(f"{src} is missing: run prepare_thirdparty.py / prepare_python.py first")
        if not (src / key).exists():
            sys.exit(f"{src / key} is missing: {name} looks incomplete")
        print(f"[{name}] hashing {src} ...", flush=True)
        files = []
        for rel, fp in iter_files(src):
            st = fp.stat()
            ck = str(fp)
            hit = cache.get(ck)
            if not hit or hit[0] != st.st_size or hit[1] != st.st_mtime_ns:
                hit = cache[ck] = [st.st_size, st.st_mtime_ns, sha256_file(fp)]
            files.append([rel, st.st_size, hit[2]])
        if key not in {f[0] for f in files}:
            sys.exit(f"[{name}] the key file {key} is not part of the component")
        cid = component_id(name, dirname, files)
        size = sum(f[1] for f in files)
        extra = []
        if name == "paraview":
            extra = sorted(c for c, _ in links["links"])  # duplicates recreated by restore_links.py
        man = {"format": FORMAT, "name": name, "dir": dirname, "id": cid, "label": label, "bytes": size,
               "files": files, "allowed_extra": extra}
        (man_dir / f"{name}.json").write_text(json.dumps(man, separators=(",", ":")), encoding="utf-8")
        archive = arch_dir / f"{name}-{cid}.7z"
        if archive.is_file():
            print(f"[{name}] unchanged ({cid}): reusing {archive.name}")
        else:
            for old in arch_dir.glob(f"{name}-*.7z*"):
                old.unlink()
            tmp = archive.with_suffix(".7z.part")
            print(f"[{name}] compressing {len(files)} files, {size / 1e9:.2f} GB ...", flush=True)
            cmd = [seven, "a", "-t7z", "-mx=9", "-mmt=on", "-mtc=off", "-mtm=off", "-mta=off", "-bd", "-y",
                   "-xr!__pycache__", "-xr!*.pyc", "-xr!*.pyo", f"-xr!{MARKER}", str(tmp), dirname]
            subprocess.run(cmd, cwd=src.parent, check=True, stdout=subprocess.DEVNULL)
            os.replace(tmp, archive)
        kb = (size + 1023) // 1024
        total_kb += kb
        up = name.upper()
        nsh += [f'!define AB_{up}_ID "{cid}"', f'!define AB_{up}_ARCHIVE "{nsis_str(str(archive))}"',
                f'!define AB_{up}_DIR "{nsis_str(dirname)}"', f'!define AB_{up}_LABEL "{nsis_str(label)}"',
                f'!define AB_{up}_KEY "{nsis_str(key.replace("/", chr(92)))}"', f"!define AB_{up}_KB {kb}"]
        print(f"[{name}] {cid}  {archive.stat().st_size / 1e6:.0f} MB archive")
    cache_file.write_text(json.dumps(cache), encoding="utf-8")
    nsh.append(f"!define AB_COMPONENTS_KB {total_kb}")
    target = Path(args.nsh) if args.nsh else ROOT / "desktop" / "build-resources" / "components.nsh"
    target.write_text("\n".join(nsh) + "\n", encoding="utf-8")
    print(f"wrote {target}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--build", default=str(ROOT / "packaging" / "build"))
    ap.add_argument("--sevenzip")
    ap.add_argument("--nsh", help="where to write the NSIS defines (default desktop/build-resources/components.nsh)")
    return build(ap.parse_args())


if __name__ == "__main__":
    sys.exit(main())
